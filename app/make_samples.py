"""Bundle the repo's example files into app/js/samples.js, so the Examples menu works even when
index.html is opened directly from disk, where a browser won't let a page fetch neighbouring files.

Also writes examples/kicad/example_ring.kicad_mod and example_die.kicad_mod, the same assembly
as example.kicad_pcb but as two footprints: the case where no GDS exists yet.

    python app/make_samples.py
"""
import base64, json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
EX = os.path.join(HERE, "..", "examples")
BOARD = os.path.join(EX, "kicad", "example.kicad_pcb")


def footprints(text):
    "Yield (properties, pads) from each top-level footprint in a board KiCad wrote or we generated."
    pos = 0
    while True:
        s = text.find("(footprint ", pos)
        if s < 0:
            return
        depth, i, quoted = 0, s, False
        while True:
            c = text[i]
            if quoted:
                if c == "\\":
                    i += 1
                elif c == '"':
                    quoted = False
            elif c == '"':
                quoted = True
            elif c == "(":
                depth += 1
            elif c == ")":
                depth -= 1
                if not depth:
                    break
            i += 1
        yield text[s:i + 1]
        pos = i + 1


def prop(fp, key):
    m = re.search(r'\(property "%s" "([^"]*)"' % key, fp)
    return m[1] if m else None


def main():
    text = open(BOARD, encoding="utf-8").read()
    die = None
    lands = []
    for fp in footprints(text):
        kind = prop(fp, "wb_kind")
        at = re.search(r"\(at ([-\d.]+) ([-\d.]+)", fp)
        if kind == "die":
            die = fp
            die_at = (float(at[1]), float(at[2]))
            outline = re.search(r'\(fp_rect\s+\(start ([-\d.]+) ([-\d.]+)\)\s+\(end ([-\d.]+) ([-\d.]+)\)', fp)
            pads = re.findall(r'\(pad "([^"]+)" smd rect\s+\(at ([-\d.]+) ([-\d.]+)\)\s+\(size ([\d.]+) ([\d.]+)\)', fp)
        elif kind == "land":
            p = re.search(r'\(pad "[^"]*" smd \w+\s+\(at [^)]*\)\s+\(size ([\d.]+) ([\d.]+)\)', fp)
            lands.append((prop(fp, "Reference"), float(at[1]), float(at[2]), p[1], p[2]))

    x0, y0, x1, y1 = map(float, outline.groups())
    cx, cy = die_at[0] + (x0 + x1) / 2, die_at[1] + (y0 + y1) / 2

    lands.sort(key=lambda r: int(r[0][1:]))
    ring = ['(footprint "example_ring"', '\t(version 20260206)', '\t(generator "wbx_make_samples")', '\t(generator_version "10.0")', '\t(layer "F.Cu")',
            '\t(descr "Land ring from example.kicad_pcb")',
            '\t(property "Reference" "J1" (at 0 -4 0) (layer "F.Fab") (effects (font (size 0.5 0.5) (thickness 0.08))))',
            '\t(property "Value" "example_ring" (at 0 4 0) (layer "F.Fab") (effects (font (size 0.5 0.5) (thickness 0.08))))',
            '\t(attr smd)']
    for ref, x, y, w, h in lands:
        ring.append(f'\t(pad "{ref[1:]}" smd rect (at {x - cx:.3f} {y - cy:.3f}) (size {w} {h}) (layers "F.Cu" "F.Mask"))')
    ring.append(")")

    # A plain third-party-style die: numbered copper pads and an outline, with nothing of ours in it.
    W, H = x1 - x0, y1 - y0
    d = ['(footprint "example_die"', '\t(version 20260206)', '\t(generator "wbx_make_samples")', '\t(generator_version "10.0")', '\t(layer "F.Cu")',
         '\t(descr "Die from example.kicad_pcb, written the way any footprint would be")',
         '\t(property "Reference" "U1" (at 0 0 0) (layer "F.Fab") (effects (font (size 0.3 0.3) (thickness 0.05))))',
         '\t(property "Value" "example_die" (at 0 0.5 0) (layer "F.Fab") (effects (font (size 0.3 0.3) (thickness 0.05))))',
         '\t(attr smd)',
         f'\t(fp_rect (start {-W / 2:.3f} {-H / 2:.3f}) (end {W / 2:.3f} {H / 2:.3f}) (stroke (width 0.02) (type solid)) (fill no) (layer "F.Fab"))']
    for num, x, y, w, h in pads:
        d.append(f'\t(pad "{num}" smd rect (at {float(x) - (x0 + x1) / 2:.3f} {float(y) - (y0 + y1) / 2:.3f}) (size {w} {h}) (layers "F.Cu"))')
    d.append(")")

    ring_path = os.path.join(EX, "kicad", "example_ring.kicad_mod")
    die_path = os.path.join(EX, "kicad", "example_die.kicad_mod")
    for path, lines in ((ring_path, ring), (die_path, d)):
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(lines) + "\n")

    b64 = lambda p: base64.b64encode(open(p, "rb").read()).decode()
    data = dict(gds=b64(os.path.join(EX, "example.gds")), board=b64(BOARD), ring=b64(ring_path), dieMod=b64(die_path))
    out = os.path.join(HERE, "js", "samples.js")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("/* Generated by app/make_samples.py. Do not edit. */\nwindow.WBX.samples = " + json.dumps(data) + ";\n")
    print("wrote", out, os.path.getsize(out), "bytes")


if __name__ == "__main__":
    main()
